import UIKit
import Messages

/// The extension's interface in Messages, built in code (no storyboard).
/// Tapping the button inserts an interactive message into the conversation's input field.
class MessagesViewController: MSMessagesAppViewController {

    private let sendButton = UIButton(type: .system)

    override func viewDidLoad() {
        super.viewDidLoad()
        view.backgroundColor = .systemBackground

        sendButton.setTitle("Send Hello", for: [])
        sendButton.titleLabel?.font = .preferredFont(forTextStyle: .headline)
        sendButton.addTarget(self, action: #selector(sendHello), for: .touchUpInside)
        sendButton.translatesAutoresizingMaskIntoConstraints = false
        view.addSubview(sendButton)
        NSLayoutConstraint.activate([
            sendButton.centerXAnchor.constraint(equalTo: view.centerXAnchor),
            sendButton.centerYAnchor.constraint(equalTo: view.centerYAnchor),
        ])
    }

    @objc private func sendHello() {
        guard let conversation = activeConversation else { return }

        let layout = MSMessageTemplateLayout()
        layout.caption = "Hello from __NAME__"

        let message = MSMessage(session: conversation.selectedMessage?.session ?? MSSession())
        message.layout = layout
        conversation.insert(message) { error in
            if let error {
                print("Failed to insert message: \(error)")
            }
        }
        dismiss()
    }

